import assert from 'node:assert/strict';
import { QS_YEAR, top100Universities, top100School, top100Coverage, normalizeDiscovery, discoveryMentors } from './dist/qs100.js';
import { schoolRows, renderSchoolsPage } from './dist/schools.js';
import { seedMentors } from './dist/mentor-data.js';

assert.equal(QS_YEAR,2026);
assert.equal(top100Universities.length,100);
assert.equal(new Set(top100Universities.map(s=>s.school)).size,100);
assert(top100Universities.every(s=>Number(s.rank.replace('=',''))<=100&&s.year===2026));
assert.equal(top100School('University of Michigan, Ann Arbor').rank,'45');
assert.equal(top100School('牛津大学').rank,'4');
assert.equal(top100School('EPFL').rank,'=22');
assert.equal(top100School('Massachusetts Institute of Technology (MIT)').rank,'1');
assert.equal(top100School('National University of Singapore (NUS)').rank,'8');
assert.equal(top100School('University of Washington').rank,'81');
assert.equal(top100School('Washington University in St. Louis'),undefined);
assert.equal(top100School('University of Copenhagen'),undefined);
assert.equal(top100School('KAIST'),undefined);
assert.equal(top100School('Unknown University'),undefined);
assert.deepEqual(normalizeDiscovery(),{rankScope:'qs100'});
assert.deepEqual(normalizeDiscovery({rankScope:'invalid'}),{rankScope:'qs100'});
const mentors=[{id:'a',name:'A',school:'University of Michigan',country:'美国'},{id:'b',name:'B',school:'University of Michigan-Ann Arbor',country:'美国'},{id:'legacy',name:'Legacy',school:'University of Copenhagen',country:'丹麦'}];
assert.deepEqual(discoveryMentors(mentors).map(m=>m.id),['a','b']);
assert.equal(discoveryMentors(mentors,{rankScope:'all'}).length,3);
const rows=top100Coverage(mentors);
assert.equal(rows.length,100);
assert.equal(rows.find(s=>s.school==='University of Michigan').mentors.length,2);
assert.equal(schoolRows(mentors,{coverage:'pending'}).length,99);
assert.equal(schoolRows(mentors,{coverage:'covered'}).length,1);
assert.equal(schoolRows(mentors,{country:'加拿大'}).length,4);
assert.equal(schoolRows(mentors,{query:'B'}).some(s=>s.school==='University of Michigan'),true);
assert.equal(schoolRows(mentors,{rankScope:'all'}).length,2,'Aliases must group into one university');
const escape=value=>String(value??'').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const html=renderSchoolsPage({mentors,settings:{rankScope:'qs100'},filters:{query:'',country:'',coverage:''},research:{keywords:[],name:'CO2RR'},qsFor:()=>null,e:escape,external:(url,label)=>`<a href="${escape(url)}">${label}</a>`,heading:()=>'',context:()=>'',empty:()=>''});
assert.equal((html.match(/class="school-cell"/g)||[]).length,100);
assert(html.includes('待补充')&&html.includes('尚未宣称覆盖全部教师'));
const expansion=seedMentors.filter(m=>m.qs100Expansion);
assert(expansion.length>=50,'The broader discovery policy must include a substantive sourced expansion');
assert.equal(new Set(seedMentors.map(m=>m.id)).size,seedMentors.length);
assert.equal(new Set(seedMentors.map(m=>m.name.toLowerCase())).size,seedMentors.length);
for(const mentor of expansion){
  assert(top100School(mentor.school),mentor.name+' must belong to the chosen ranking year/universe');
  assert.equal(mentor.qs.year,2026);
  assert(mentor.url.startsWith('https://')&&mentor.researchSource.startsWith('https://'));
  assert(mentor.title&&mentor.summary&&mentor.keywords.length&&mentor.researchAreas.length);
  assert(Array.isArray(mentor.papers)&&Array.isArray(mentor.relations));
  assert.equal(mentor.team.chineseStudents,null);
  assert.equal(mentor.team.chineseFaculty,null);
}
console.log('QS100 checks passed: exact universe, ties/year, school aliases, default scope, legacy records retained and honest per-school coverage.');
