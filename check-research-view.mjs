import assert from 'node:assert/strict';
import {seedMentors} from './dist/mentor-data.js';
import {defaultResearch,normalizeResearch,researchView,filterMentorPapers} from './dist/research.js';
import {analyzeProfile,matchMentor} from './dist/profile.js';

const before=JSON.stringify(seedMentors),co2=researchView(seedMentors,defaultResearch());
const orrResearch=normalizeResearch({name:'氧还原',shortName:'ORR',keywords:['ORR']});
const orr=researchView(seedMentors,orrResearch);
assert.equal(new Set(seedMentors.map(m=>m.id)).size,24);
assert.deepEqual([co2.mentors.length,co2.papers.length],[18,25]);
assert.deepEqual([orr.mentors.length,orr.papers.length],[7,7]);
assert.equal(new Set(orr.mentors.map(m=>m.school)).size,7);
assert(!orr.mentors.some(m=>m.id==='yang'));
assert(orr.mentors.find(m=>m.id==='strasser').summary.includes('氧还原'));
assert(orr.mentors.find(m=>m.id==='strasser').topics[0].includes('ORR'));
assert(orr.mentors.find(m=>m.id==='strasser').relations.filter(r=>r.type==='合作').every(r=>r.name==='Frédéric Jaouen'));
assert(orr.papers.every(p=>p.researchAreas.includes('orr')));
assert.equal(orr.papers.find(p=>p.url.includes('3c03033')).mentors.length,2);
assert.equal(researchView(seedMentors,{...orrResearch,keywords:['oxygen reduction']}).papers.length,7);
assert.equal(researchView(seedMentors,{...orrResearch,keywords:['固态电池']}).mentors.length,0);
assert.equal(researchView([{id:'corr',summary:'CORR only'}],orrResearch).mentors.length,0);
assert.equal(matchMentor(analyzeProfile('ORR 氧还原'),orr.mentors.find(m=>m.id==='shao-horn')).score,100);
const mixed=[{id:'mixed',summary:'ORR and CO2RR',papers:[{title:'Oxygen reduction with urea',year:2024},{title:'CO2 electroreduction',year:2025}]}];
assert.equal(researchView(mixed,orrResearch).papers.length,1);
assert.equal(researchView(mixed,{...orrResearch,excludedKeywords:['urea']}).papers.length,0);
assert.equal(filterMentorPapers(orr.papers,{journal:'Journal of the American Chemical Society',year:'2025',mentor:'wu-gang'}).length,1);
assert.equal(filterMentorPapers(orr.papers,{journal:'Journal of the American Chemical Society',year:'2024',mentor:'wu-gang'}).length,0);
assert.equal(filterMentorPapers(orr.papers,{mentor:'jaouen',journal:'Journal of the American Chemical Society'}).length,2);
const chosen=orr.papers[0];
assert.deepEqual(filterMentorPapers(orr.papers,{savedOnly:true,saved:[chosen.key]}),[chosen]);
assert.equal(JSON.stringify(seedMentors),before,'Discovery must not mutate full records used by saved applications');
console.log('Research view checks passed: isolated fields, shared authors, independent papers, exclusions, combined dropdowns, unchanged source records.');
