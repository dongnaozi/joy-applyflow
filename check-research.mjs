import assert from 'node:assert/strict';
import {defaultResearch,normalizeResearch,matchesResearch,researchQuery} from './dist/research.js';
assert.deepEqual(normalizeResearch(),defaultResearch());
const first=defaultResearch(),second=defaultResearch();first.keywords.push('x');assert.equal(second.keywords.length,0);
const custom=normalizeResearch({name:'氧还原',shortName:'ORR',keywords:'ORR，oxygen reduction;orr\n 氧还原',excludedKeywords:['urea','UREA']});
assert.deepEqual(custom.keywords,['ORR','oxygen reduction','氧还原']);assert.deepEqual(custom.excludedKeywords,['urea']);
assert(matchesResearch('Oxygen reduction at a catalyst',custom));assert(!matchesResearch('CO2 reduction with urea',custom));assert(!matchesResearch('CORR only',custom));
assert(!matchesResearch('other chemistry',normalizeResearch({name:'氢还原',keywords:['HER']})));
assert(matchesResearch('CO 2 RR is measured',normalizeResearch({name:'CO₂ 电还原',keywords:['CO2RR']})));
assert(matchesResearch('CO 2 electroreduction',normalizeResearch({name:'CO₂ 电还原',keywords:['CO2']})));
assert(!matchesResearch('Culture study',normalizeResearch({name:'铜催化',keywords:['Cu']})));
assert(matchesResearch('Cu-based catalyst',normalizeResearch({name:'铜催化',keywords:['Cu']})));
assert.throws(()=>normalizeResearch({name:'固态电池'}));assert.throws(()=>normalizeResearch({name:'x',keywords:['a'.repeat(81)]}));
assert.throws(()=>normalizeResearch({name:'x',keywords:Array.from({length:21},(_,i)=>'k'+i)}));
const hostile=normalizeResearch(JSON.parse('{"name":"氧还原","keywords":["ORR"],"__proto__":{"polluted":true}}'));assert.equal({}.polluted,undefined);assert(!Object.hasOwn(hostile,'__proto__'));
assert.equal(new URLSearchParams(researchQuery(custom)).getAll('kw').length,3);
assert.deepEqual(normalizeResearch(JSON.parse(JSON.stringify(custom))),custom);
